#[test]
fn options_clause_ignored() {
    let (mut storage, mut txn, mut bloom, mut ctx) = setup();

    // Options inside parentheses are parsed but silently ignored;
    // sequence still starts at 1 with increment 1.
    run_ok(
        "CREATE TABLE t (\
            id INT GENERATED ALWAYS AS IDENTITY (START WITH 100 INCREMENT BY 10), \
            v TEXT\
        )",
        &mut storage,
        &mut txn,
        &mut bloom,
        &mut ctx,
    );
    run_ok(
        "INSERT INTO t(v) VALUES ('x')",
        &mut storage,
        &mut txn,
        &mut bloom,
        &mut ctx,
    );

    let result = rows(
        "SELECT id FROM t",
        &mut storage,
        &mut txn,
        &mut bloom,
        &mut ctx,
    );
    assert_eq!(result[0][0], Value::Int(1)); // not 100 — options are ignored
}

#[test]
fn show_columns_always_identity() {
    let (mut storage, mut txn, mut bloom, mut ctx) = setup();

    run_ok(
        "CREATE TABLE t (id INT GENERATED ALWAYS AS IDENTITY, v TEXT)",
        &mut storage,
        &mut txn,
        &mut bloom,
        &mut ctx,
    );

    let result = rows(
        "SHOW COLUMNS FROM t",
        &mut storage,
        &mut txn,
        &mut bloom,
        &mut ctx,
    );
    // Find the `id` row; Extra is the 6th column (index 5).
    let id_row = result
        .iter()
        .find(|r| matches!(&r[0], Value::Text(s) if s == "id"))
        .expect("id column should exist");
    let extra = match &id_row[5] {
        Value::Text(s) => s.as_str(),
        other => panic!("expected text Extra, got {other:?}"),
    };
    assert_eq!(extra, "GENERATED ALWAYS AS IDENTITY");
}

