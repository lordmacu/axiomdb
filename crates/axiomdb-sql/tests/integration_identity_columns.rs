    let (mut storage, mut txn, mut bloom, mut ctx) = setup();

    run_ok(
        "CREATE TABLE t (id INT GENERATED ALWAYS AS IDENTITY, v TEXT)",
        &mut storage,
        &mut txn,
        &mut bloom,
        &mut ctx,
    );

    let err = run_ctx(
        "INSERT INTO t(id, v) VALUES (42, 'x')",
        &mut storage,
        &mut txn,
        &mut bloom,
        &mut ctx,
    )
    .expect_err("INSERT with explicit value should be rejected");
    let msg = format!("{err:?}");
