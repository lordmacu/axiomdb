//! Phase 24.1c — `GENERATED ALWAYS|BY DEFAULT AS IDENTITY` integration tests.
//!
//! Covers SQL:2003 identity column semantics:
//! - ALWAYS: explicit INSERT values rejected; NULL/missing auto-generate.
//! - BY DEFAULT: explicit values accepted; NULL/missing auto-generate.
//! - INT and BIGINT identity columns.
//! - Options clause (`(START WITH ...)`) parsed and ignored.
//! - SHOW COLUMNS + SHOW CREATE TABLE display the correct identity syntax.
//! - Existing AUTO_INCREMENT columns continue to display "auto_increment".

mod common;

use axiomdb_sql::{bloom::BloomRegistry, QueryResult, SessionContext};
use axiomdb_storage::MemoryStorage;
use axiomdb_types::Value;
use axiomdb_wal::TxnManager;

use common::*;

fn setup() -> (MemoryStorage, TxnManager, BloomRegistry, SessionContext) {
    setup_ctx()
}

fn run_ok(
    sql: &str,
    storage: &mut MemoryStorage,
    txn: &mut TxnManager,
    bloom: &mut BloomRegistry,
    ctx: &mut SessionContext,
) -> QueryResult {
    run_ctx(sql, storage, txn, bloom, ctx)
        .unwrap_or_else(|e| panic!("SQL failed: {sql}\nError: {e:?}"))
}

fn rows(
    sql: &str,
    storage: &mut MemoryStorage,
    txn: &mut TxnManager,
    bloom: &mut BloomRegistry,
    ctx: &mut SessionContext,
) -> Vec<Vec<Value>> {
    match run_ok(sql, storage, txn, bloom, ctx) {
        QueryResult::Rows { rows, .. } => rows,
        other => panic!("expected rows, got {other:?}"),
    }
}

#[test]
fn always_identity_basic_autoincrement() {
    let (mut storage, mut txn, mut bloom, mut ctx) = setup();

    run_ok(
        "CREATE TABLE t (id INT GENERATED ALWAYS AS IDENTITY, v TEXT)",
        &mut storage,
        &mut txn,
        &mut bloom,
        &mut ctx,
    );
    run_ok(
        "INSERT INTO t(v) VALUES ('a')",
        &mut storage,
        &mut txn,
        &mut bloom,
        &mut ctx,
    );
    run_ok(
        "INSERT INTO t(v) VALUES ('b')",
        &mut storage,
        &mut txn,
        &mut bloom,
        &mut ctx,
    );

    let result = rows(
        "SELECT id, v FROM t ORDER BY id",
        &mut storage,
        &mut txn,
        &mut bloom,
        &mut ctx,
    );
    assert_eq!(result.len(), 2);
    assert_eq!(result[0][0], Value::Int(1));
    assert_eq!(result[1][0], Value::Int(2));
}

