#[test]
fn always_identity_explicit_zero_treated_as_auto() {
    let (mut storage, mut txn, mut bloom, mut ctx) = setup();

    run_ok(
        "CREATE TABLE t (id INT GENERATED ALWAYS AS IDENTITY, v TEXT)",
        &mut storage,
        &mut txn,
        &mut bloom,
        &mut ctx,
    );
    // Explicit 0 is the MySQL-style auto trigger; for ALWAYS this is
    // treated as "auto-generate" rather than a rejection.
    run_ok(
        "INSERT INTO t(id, v) VALUES (0, 'zero')",
        &mut storage,
        &mut txn,
        &mut bloom,
        &mut ctx,
    );
    let result = rows(
        "SELECT id, v FROM t",
        &mut storage,
        &mut txn,
        &mut bloom,
        &mut ctx,
    );
    assert_eq!(result[0][0], Value::Int(1));
}
